"""Deterministic RLM plan and code scaffold; this module executes no tools or model calls."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class RlmPlan:
    plan: str
    code: str
    rationale: str


def build_rlm_plan(question: str, context: str = "", tools: list[str] | None = None) -> RlmPlan:
    """Return an RLM plan: a reasoning scaffold plus an executable code stub."""
    tools = tools if tools is not None else []
    tool_lines = "\n".join(f"#   - use {t} via the runtime tool interface" for t in tools)
    code = (
        "def solve():\n"
        "    # RLM loop: reason, then act, then verify.\n"
        "    plan = []\n"
        f"    question = {question!r}\n"
        f"    context = {context!r}\n"
        "    # (1) state the sub-goals\n"
        "    # (2) call tools as needed\n"
        "    # (3) verify the answer against the question\n"
        "    return {\"answer\": None, \"steps\": plan}\n"
    )
    plan = (
        "You are operating as an RLM agent. Decompose the question into "
        "sub-goals, invoke the available tools to gather evidence, and only "
        "then synthesize a final answer. Tools available:\n"
        f"{tool_lines}"
    )
    return RlmPlan(plan=plan, code=code, rationale="Generated by dsh-dspy RLM planner.")


def score_answer(answer: str, constraint: str | None = None) -> float:
    if not answer:
        return 0.0
    if not constraint:
        return 1.0
    return 1.0 if constraint.lower() in answer.lower() else 0.0
